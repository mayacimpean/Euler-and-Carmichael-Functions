def carmichael_lambda_prime_power(p, k):
  """Calculates λ(p^k) for a prime p and exponent k."""
  if p == 2:
    if k == 1: return 1
    if k == 2: return 2
    if k >= 3: return 2**(k-2)
  else: # p is an odd prime
    return p**(k-1) * (p-1)

def gcd(a, b):
  """Calculates the Greatest Common Divider of two numbers using the Euclidean algorithm."""
  while b:
    a, b = b, a % b
  return a

def lcm(a, b):
  """Calculates the Least Common Multiple of two numbers."""
  if a == 0 or b == 0: return 0
  return abs(a * b) // gcd(a, b)




