def prime_factorization(n):
  """Computes the prime factorization of a number n."""
  factors = {}
  d = 2
  temp = n
  while d * d <= temp:
    while temp % d == 0:
      factors[d] = factors.get(d, 0) + 1
      temp //= d
    d += 1
  if temp > 1:
    factors[temp] = factors.get(temp, 0) + 1
  return factors

def carmichael_function(n):
  """Calculates the Carmichael function λ(n)."""
  if n == 1: return 1

  factors = prime_factorization(n)

  # Calculate lambda for each prime power factor
  lambdas = []
  for p, k in factors.items():
    lambdas.append(carmichael_lambda_prime_power(p, k))

  # Compute the LCM of all individual lambdas
  result = 1
  for val in lambdas:
    result = lcm(result, val)
  return result

