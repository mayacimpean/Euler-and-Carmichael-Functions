# =============================================================
# KARATSUBA MULTIPLICATION
# =============================================================

def karatsuba(x, y):
    """
    Multiply two non-negative integers using the Karatsuba algorithm.
    """

    # For small numbers, normal multiplication is faster.
    if x < 1024 or y < 1024:
        return x * y

    n = max(x.bit_length(), y.bit_length())
    m = n // 2

    mask = (1 << m) - 1

    x1, x0 = x >> m, x & mask
    y1, y0 = y >> m, y & mask

    z2 = karatsuba(x1, y1)
    z0 = karatsuba(x0, y0)
    z1 = karatsuba(x1 + x0, y1 + y0) - z2 - z0

    return (z2 << (2 * m)) + (z1 << m) + z0


# =============================================================
# PRIME TEST
# =============================================================

def is_prime(n):
    """
    Return True if n is prime and False otherwise.
    """

    if n < 2:
        return False

    if n == 2:
        return True

    if n % 2 == 0:
        return False

    # Trial division by odd integers up to sqrt(n).
    for i in range(3, isqrt(n) + 1, 2):

        if n % i == 0:
            return False

    return True


# =============================================================
# EXTENDED EUCLIDEAN ALGORITHM
# =============================================================

def extended_gcd(a, b):
    """
    Return gcd(a, b) together with x and y such that:

        ax + by = gcd(a, b)
    """

    if b == 0:
        return a, 1, 0

    g, x1, y1 = extended_gcd(
        b,
        a % b
    )

    x = y1
    y = x1 - (a // b) * y1

    return g, x, y


# =============================================================
# MODULAR INVERSE
# =============================================================

def mod_inverse(a, m):
    """
    Find the modular inverse of a modulo m using the
    Extended Euclidean Algorithm.

    Finds d such that:

        a*d ≡ 1 (mod m)
    """

    g, x, _ = extended_gcd(a, m)

    if g != 1:
        return -1

    return x % m


# =============================================================
# LEAST COMMON MULTIPLE
# =============================================================

def lcm(a, b):
    """
    Return the least common multiple of a and b.
    """

    return abs(a * b) // gcd(a, b)


# =============================================================
# GENERATE LIST OF CANDIDATE PRIMES
# =============================================================

def generate_prime_list(keysize):
    """
    Generate candidate primes for an RSA modulus of
    approximately the requested bit length.
    """

    start = 1 << (keysize // 2 - 1)
    stop = 1 << (keysize // 2 + 1)

    if start >= stop:
        raise ValueError(
            "Key size too small."
        )

    primes = [
        number
        for number in range(start, stop + 1)
        if is_prime(number)
    ]

    return primes


# =============================================================
# GENERATE p, q AND n
# =============================================================

def generate_prime_pair(keysize, primes):
    """
    Select distinct primes p and q such that:

        n = p*q

    has the requested bit length.
    """

    nMin = 1 << (keysize - 1)
    nMax = (1 << keysize) - 1

    candidates = list(primes)
    random.shuffle(candidates)

    for p in candidates:

        q_values = [
            q
            for q in primes

            if q != p

            and nMin
            <= karatsuba(p, q)
            <= nMax
        ]

        if q_values:

            q = random.choice(q_values)

            n = karatsuba(
                p,
                q
            )

            return p, q, n

    raise ValueError(
        "Could not find a suitable prime pair."
    )


# =============================================================
# CHOOSE COMMON PUBLIC EXPONENT e
# =============================================================

def choose_public_exponent(phi):
    """
    Choose e such that:

        gcd(e, phi(n)) = 1

    Since lambda(n) divides phi(n), this also ensures
    that e is coprime to lambda(n).
    """

    while True:

        e = random.randrange(
            2,
            phi
        )

        if gcd(e, phi) == 1:
            return e


# =============================================================
# EULER KEY DERIVATION
# =============================================================

def generate_euler_private_key(p, q, e):
    """
    Use Euler's totient function:

        phi(n) = (p - 1)(q - 1)

    and calculate:

        d = e^(-1) mod phi(n)
    """

    phi = karatsuba(
        p - 1,
        q - 1
    )

    d = mod_inverse(
        e,
        phi
    )

    if d == -1:
        raise ValueError(
            "Euler modular inverse does not exist."
        )

    return phi, d


# =============================================================
# CARMICHAEL KEY DERIVATION
# =============================================================

def generate_carmichael_private_key(p, q, e):
    """
    Use the Carmichael function:

        lambda(n) = lcm(p - 1, q - 1)

    and calculate:

        d = e^(-1) mod lambda(n)
    """

    lambda_n = lcm(
        p - 1,
        q - 1
    )

    d = mod_inverse(
        e,
        lambda_n
    )

    if d == -1:
        raise ValueError(
            "Carmichael modular inverse does not exist."
        )

    return lambda_n, d


# =============================================================
# ENCRYPTION
# =============================================================

def encrypt(plaintext, public_key):
    """
    Encrypt plaintext using:

        c = m^e mod n
    """

    e, n = public_key

    return [
        pow(ord(character), e, n)
        for character in plaintext
    ]


# =============================================================
# DECRYPTION
# =============================================================

def decrypt(ciphertext, private_key):
    """
    Decrypt ciphertext using:

        m = c^d mod n
    """

    d, n = private_key

    return ''.join(
        chr(pow(character, d, n))
        for character in ciphertext
    )


